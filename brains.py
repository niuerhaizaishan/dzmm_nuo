def _call_llm(system_prompt: str, user_content: str,
              api_key: str = DEFAULT_KEY, max_tokens: int = 100,
              timeout: int = 30, model: str = None) -> str:
    """调用 DeepSeek，解析 JSON 响应。

    这里是全部提示词的唯一出口：分群人设在这里注入（默认群原样返回，零开销）。
    """
    try:
        import personas
        system_prompt = personas.apply_persona(system_prompt)
    except Exception:
        pass
    payload = [
        {"role": "system", "content": system_prompt},
        {"role": "user", "content": user_content},
    ]
    resp = requests.post(DEEPSEEK_URL, json={
        "model": model or DEEPSEEK_MODEL,
        "messages": payload,
        "max_tokens": max_tokens,
        "temperature": 0.7,
        "thinking": {"type": "disabled"},
    }, headers={
        "Authorization": "Bearer " + api_key,
        "Content-Type": "application/json",
    }, timeout=timeout)
    data = resp.json()
    try:
        reply = data["choices"][0]["message"]["content"]
    except Exception:
        reply = ""
    reply = (reply or "").strip()
    # 清掉所有 🤖，bot.py 会统一加一个
    reply = reply.replace("🤖", "").strip()
    return reply


def generate_reply(messages: list[dict], api_key: str = DEFAULT_KEY,
                   max_tokens: int = None) -> str:
    """群内闲聊/房间对话的回复。

    `max_tokens` 可覆盖（默认 400）：玫瑰房的人设要求"4～8 句"，400 token 容易
    把话说到一半就截断 —— 由调用方按群传 `tuning: room.reply_max_tokens`。
    """
    chat = []
    for m in messages[-10:]:
        name = m.get("sender", "")
        text = m.get("text", "")
        if name:
            chat.append(name[:8] + ": " + text)
        else:
            chat.append(text)
    context = "\n".join(chat)
    return _call_llm(CMD_PROMPT, context, api_key,
                     max_tokens=int(max_tokens or 400))


